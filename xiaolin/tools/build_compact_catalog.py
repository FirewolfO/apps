def topic(title, slug, summary, answer, points, follow_ups, pitfall,
          source_url, diagram_title="", diagram_nodes=()):
    value = {
        "title": title,
        "url": COMPACT_ORIGIN + slug,
        "summary": summary,
        "answer": answer,
        "keyPoints": list(points),
        "followUps": list(follow_ups),
        "pitfall": pitfall,
        "sourceUrl": source_url,
    }
    if diagram_nodes:
        value["diagram"] = {"title": diagram_title, "nodes": list(diagram_nodes)}
    return value


def section(title, *articles):
    return {"title": title, "articles": list(articles)}


def book(title, description, source_url, *sections):
    return {
        "title": title,
        "description": description,
        "homeUrl": source_url,
        "sections": list(sections),
    }


def group(title, description, *books):
    return {"title": title, "description": description, "books": list(books)}


