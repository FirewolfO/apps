def validate(catalog):
    urls = set()
    article_count = 0
    diagram_count = 0
    for item_group in catalog["groups"]:
        if not item_group["books"]:
            raise RuntimeError("empty group: " + item_group["title"])
        for item_book in item_group["books"]:
            for item_section in item_book["sections"]:
                for article in item_section["articles"]:
                    article_count += 1
                    if article["url"] in urls:
                        raise RuntimeError("duplicate compact URL: " + article["url"])
                    urls.add(article["url"])
                    for required in ("title", "summary", "answer", "keyPoints", "followUps", "pitfall", "sourceUrl"):
                        if not article[required]:
                            raise RuntimeError(f"{article['title']} missing {required}")
                    if "diagram" in article:
                        diagram_count += 1
    if article_count < 60:
        raise RuntimeError(f"compact catalog too small: {article_count}")
    if diagram_count < 15:
        raise RuntimeError(f"not enough diagrams: {diagram_count}")
    return article_count, diagram_count


def main():
    catalog = build_catalog()
    article_count, diagram_count = validate(catalog)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(json.dumps(catalog, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"精简版: {len(catalog['groups'])} 个系列，{article_count} 个重点，{diagram_count} 张图示 -> {OUTPUT}")


if __name__ == "__main__":
    main()
